CREATE FUNCTION proteger_revision_cerrada() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            IF TG_OP = 'DELETE' OR OLD.cerrada THEN
                RAISE EXCEPTION 'No se permite eliminar revisiones ni modificar revisiones cerradas';
            END IF;
            RETURN NEW;
        END;
        $$;

CREATE FUNCTION verificar_revision_actual() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE revision_cerrada boolean;
        BEGIN
            IF NEW.revision_actual_id IS NOT NULL THEN
                SELECT cerrada INTO revision_cerrada FROM revisiones_ubicacion
                WHERE id = NEW.revision_actual_id AND ubicacion_id = NEW.id FOR UPDATE;
                IF NOT FOUND OR NOT revision_cerrada THEN
                    RAISE EXCEPTION 'La revisión actual debe pertenecer a la ubicación y estar cerrada';
                END IF;
            END IF;
            RETURN NEW;
        END;
        $$;

CREATE FUNCTION preparar_fotografia() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE actor bigint;
        BEGIN
            actor := NULLIF(current_setting('app.usuario_id', true), '')::bigint;
            IF actor IS NULL THEN
                RAISE EXCEPTION 'Falta el usuario autenticado para modificar la fotografía';
            END IF;
            IF TG_OP = 'DELETE' THEN
                RETURN OLD;
            ELSIF TG_OP = 'INSERT' THEN
                NEW.registrado_por := actor;
                NEW.registrado_en := clock_timestamp();
                NEW.actualizado_por := NULL;
                NEW.actualizado_en := NULL;
            ELSE
                IF (NEW.id, NEW.ubicacion_id, NEW.registrado_por, NEW.registrado_en)
                   IS DISTINCT FROM
                   (OLD.id, OLD.ubicacion_id, OLD.registrado_por, OLD.registrado_en) THEN
                    RAISE EXCEPTION 'No se permite cambiar la identidad ni el registro original';
                END IF;
                NEW.actualizado_por := actor;
                NEW.actualizado_en := clock_timestamp();
            END IF;
            RETURN NEW;
        END;
        $$;

CREATE FUNCTION auditar_fotografia() RETURNS trigger
        LANGUAGE plpgsql AS $$
        DECLARE
            actor bigint := NULLIF(current_setting('app.usuario_id', true), '')::bigint;
            accion_evento text;
            foto_id bigint;
            ubicacion_evento bigint;
        BEGIN
            IF TG_OP = 'INSERT' THEN
                accion_evento := 'CREAR_FOTOGRAFIA';
                foto_id := NEW.id;
                ubicacion_evento := NEW.ubicacion_id;
            ELSIF TG_OP = 'DELETE' THEN
                accion_evento := 'ELIMINAR_FOTOGRAFIA';
                foto_id := OLD.id;
                ubicacion_evento := OLD.ubicacion_id;
            ELSE
                IF (NEW.storage_bucket, NEW.storage_clave) IS DISTINCT FROM
                   (OLD.storage_bucket, OLD.storage_clave) THEN
                    accion_evento := 'REEMPLAZAR_FOTOGRAFIA';
                ELSE
                    accion_evento := 'ACTUALIZAR_FOTOGRAFIA';
                END IF;
                foto_id := NEW.id;
                ubicacion_evento := NEW.ubicacion_id;
            END IF;
            INSERT INTO auditoria (usuario_id, ubicacion_id, accion, ocurrido_en, detalles)
            VALUES (actor, ubicacion_evento, accion_evento, clock_timestamp(),
                    jsonb_build_object('fotografia_id', foto_id));
            RETURN NULL;
        END;
        $$;

